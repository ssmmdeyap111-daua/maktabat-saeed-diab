// دالة العرض العام
function render() {
    // 1. عرض الأقسام في صفحة الفهرس (lessons.html)
    const catContainer = document.getElementById('lessons-list');
    if (catContainer) {
        catContainer.innerHTML = mainCategories.map(cat => `
            <a href="${cat.link}" class="lesson-card">
                <div class="icon-box"><i class="${cat.icon}"></i></div>
                <div class="lesson-info">
                    <h3>${cat.title}</h3>
                    <p>${cat.desc}</p>
                </div>
            </a>
        `).join('');
    }

    // 2. عرض دروس العقيدة (aqidah.html)
    displayAudioList(tawheedLessons, 'aqidah-list', 'tawheed');

    // 3. عرض دروس الحديث (hadith.html)
    displayAudioList(hadithLessons, 'hadith-list', 'hadith');

    // 4. عرض دروس الفرائض (faraid.html)
    displayAudioList(faraidLessons, 'faraid-list', 'faraid');
}

// دالة مساعدة لعرض قوائم الصوت بتنسيق الأيقونات الجديد الأزرق الفاتح الـ 3D
function displayAudioList(data, containerId, folder) {
    const container = document.getElementById(containerId);
    if (!container) return;
    container.innerHTML = data.map(lesson => `
        <div class="lesson-item">
            <div class="lesson-info">
                <i class="fas fa-play-circle" style="color: #4dafff; text-shadow: 1px 1px 0px #2575fc, 2px 2px 3px rgba(0,0,0,0.15); font-size: 1.3rem;"></i>
                <span class="lesson-title">${lesson.title}</span>
            </div>
            <audio controls preload="none">
                <source src="audio/${folder}/${lesson.file}" type="audio/mpeg">
            </audio>
            <a href="audio/${folder}/${lesson.file}" download class="btn-download-3d">
                 <i class="fas fa-arrow-down"></i>
            </a>
        </div>
    `).join('');
}

document.addEventListener('DOMContentLoaded', render);
